/**
 * Nettoie le code généré par un LLM
 * (Retire les marqueurs markdown, espaces superflus, explications, etc.)
 *
 * @param code - Code brut généré par le LLM
 * @returns Code nettoyé
 */
function cleanGeneratedCode(code: string): string {
  // Retirer les blocs de code markdown (```typescript, ```, etc.)
  let cleaned = code.replace(/```typescript\n?/g, "");
  cleaned = cleaned.replace(/```ts\n?/g, "");
  cleaned = cleaned.replace(/```\n?/g, "");

  // Retirer les espaces en début/fin
  cleaned = cleaned.trim();

  // Trouver la dernière occurrence de "});" qui marque la fin du code
  const lastClosingBrace = cleaned.lastIndexOf("});");

  if (lastClosingBrace !== -1) {
    // Garder tout jusqu'à la fin du dernier bloc de code
    cleaned = cleaned.substring(0, lastClosingBrace + 3); // +3 pour inclure "});"
  }

  // Supprimer tout texte explicatif après le code
  // Chercher les patterns typiques d'explications en français
  const explanationPatterns = [
    /\n\n[A-Z][^`]*$/, // Texte commençant par majuscule après double saut de ligne
    /\n\nCe code[^]*$/, // Explication commençant par "Ce code"
    /\n\nLe code[^]*$/, // Explication commençant par "Le code"
    /\n\nExplication[^]*$/, // Section d'explication
  ];

  for (const pattern of explanationPatterns) {
    cleaned = cleaned.replace(pattern, "");
  }

  // S'assurer qu'il y a un import Playwright
  if (!cleaned.includes("from '@playwright/test'")) {
    cleaned = "import { test, expect } from '@playwright/test';\n\n" + cleaned;
  }

  // Retirer à nouveau les espaces en début/fin après le nettoyage
  cleaned = cleaned.trim();

  return cleaned;
}

/**
 * Valide que le code généré est syntaxiquement correct
 *
 * @param code - Code à valider
 * @returns true si le code semble valide
 */
export function validateGeneratedCode(code: string): boolean {
  // Vérifications basiques
  if (!code || code.trim().length === 0) {
    return false;
  }

  // Doit contenir un import Playwright
  if (!code.includes("@playwright/test")) {
    return false;
  }

  // Doit contenir au moins une définition de test
  if (!code.includes("test(")) {
    return false;
  }

  // Doit contenir une fonction async
  if (!code.includes("async")) {
    return false;
  }

  return true;
}

/**
 * Extrait les métadonnées du code généré
 *
 * @param code - Code de test
 * @returns Métadonnées extraites
 */
export function extractCodeMetadata(code: string) {
  const urlMatch = code.match(/goto\(['"](.+?)['"]\)/);
  const testNameMatch = code.match(/test\(['"](.+?)['"]/);

  return {
    url: urlMatch?.[1],
    testName: testNameMatch?.[1],
    hasImports: code.includes("import"),
    hasAsync: code.includes("async"),
    hasExpect: code.includes("expect"),
    lineCount: code.split("\n").length,
  };
}

/**
 * Estime la durée d'exécution du test
 * (Analyse basique du code pour estimer le temps)
 *
 * @param code - Code du test
 * @returns Durée estimée en millisecondes
 */
export function estimateTestDuration(code: string): number {
  let duration = 2000; // Base: 2 secondes

  // Ajouter du temps pour chaque action
  const clickCount = (code.match(/\.click\(/g) || []).length;
  const fillCount = (code.match(/\.fill\(/g) || []).length;
  const waitCount = (code.match(/\.wait/g) || []).length;
  const expectCount = (code.match(/expect\(/g) || []).length;

  duration += clickCount * 500; // 500ms par clic
  duration += fillCount * 300; // 300ms par remplissage
  duration += waitCount * 1000; // 1s par wait
  duration += expectCount * 200; // 200ms par assertion

  return duration;
}
